"""Reproduce the October fleet cohort using a bounded, automatically cleaned scratch directory."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile

# A single machine only needs one numerical worker for this streaming replay.
for name in ('OPENBLAS_NUM_THREADS','OMP_NUM_THREADS','MKL_NUM_THREADS','NUMBA_NUM_THREADS'):
    os.environ.setdefault(name,'1')

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from tools.fleet_cases import (LiveOverlay, Router, TimetableMatcher, geometry, manifest,
                               neighbor, shard, write_day as score_day)
from tools.fleet_hourly import write_day as extract_day
from tools.month_boarding_scan import ARCHIVE, MONTH, archive_members, save


def replay(args):
    args.output.mkdir(parents=True,exist_ok=True)
    r = Router(ROOT/'delhi_buses_static_gtfs_v1.zip',ROOT/'data',None,None)
    g, matcher = geometry(r), TimetableMatcher(r,LiveOverlay(None,ROOT/'data').bind(r))
    protocol = manifest(r)
    signature = hashlib.sha256(json.dumps(protocol,sort_keys=True).encode()).hexdigest()
    marker = args.output/'manifest.json'
    if marker.exists() and json.loads(marker.read_text())['signature']!=signature:
        raise ValueError('Existing fleet evidence was generated by a different protocol.')
    if not marker.exists():
        save(marker,dict(protocol,signature=signature))
    pending = set()
    for day in MONTH:
        target = args.output/f'{day}.json.gz'
        if not target.exists():
            pending.add(day)
            continue
        with gzip.open(target,'rt',encoding='utf-8') as f:
            evidence = json.load(f)
        if not (evidence.get('complete') and evidence['day']==day and evidence['signature']==signature
                and len(evidence['hours'])==24):
            raise ValueError('Existing daily result failed completeness or provenance checks: '+day)
        del evidence
    if not pending:
        return
    needed = {which for d in pending for which in (neighbor(d,-1)[0],d,neighbor(d,24)[0]) if which in MONTH}
    members = archive_members(args.seven,args.archive)
    # This random directory contains only files created by this invocation. The
    # user's original archive, earlier extracts and any shared scratch are separate.
    with tempfile.TemporaryDirectory(prefix='delhi-fleet-',dir=args.scratch_parent) as temporary:
        scratch = Path(temporary)
        # Keep the one expanded SQLite input on the selected scratch volume too.
        previous_temp = tempfile.tempdir
        tempfile.tempdir = str(scratch)
        try:
            process_days(args,scratch,needed,pending,members,g,matcher,signature)
        finally:
            tempfile.tempdir = previous_temp


def process_days(args,scratch,needed,pending,members,g,matcher,signature):
    for index,day in enumerate(MONTH):
        if day in needed:
            extract_day(day,args.archive,members,args.seven,scratch)
        if index:
            previous = MONTH[index-1]
            if previous in pending:
                score_day(scratch,previous,g,matcher,args.output,signature)
            # Only the previous 23h shard can still affect today's 00h replay.
            for h in range(23):
                shard(scratch,previous,h).unlink(missing_ok=True)
            if index>=2:
                shard(scratch,MONTH[index-2],23).unlink(missing_ok=True)
    if MONTH[-1] in pending:
        score_day(scratch,MONTH[-1],g,matcher,args.output,signature)


if __name__=='__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'data'/'fleet-cases')
    parser.add_argument('--scratch-parent',type=Path,default=Path(tempfile.gettempdir()))
    parser.add_argument('--seven',type=Path,default=Path('C:/Program Files/7-Zip/7z.exe'))
    parser.add_argument('--archive',type=Path,default=ARCHIVE)
    replay(parser.parse_args())
